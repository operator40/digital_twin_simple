ALTER TABLE public.asset_failure_types OWNER TO dt_admin;

CREATE TABLE public.sensors (
    sensor_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sensor_name TEXT NOT NULL,
    measurement_frequency REAL,
    ranges_id BIGINT,
    type_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    metric_function_id BIGINT,
    CONSTRAINT pk_sensors PRIMARY KEY (sensor_id),
    CONSTRAINT fk_sensors_ranges
        FOREIGN KEY (ranges_id) REFERENCES public.ranges (ranges_id),
    CONSTRAINT fk_sensors_sensor_types
        FOREIGN KEY (type_id) REFERENCES public.sensor_types (type_id),
    CONSTRAINT fk_sensors_assets
        FOREIGN KEY (asset_id) REFERENCES public.assets (asset_id)
);

ALTER TABLE public.sensors OWNER TO dt_admin;

CREATE TABLE public.measurements (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sensor_id BIGINT NOT NULL,
    "time" TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    value REAL NOT NULL,
    CONSTRAINT pk_measurements PRIMARY KEY (measurement_id, "time"),
    CONSTRAINT fk_measurements_sensors
        FOREIGN KEY (sensor_id) REFERENCES public.sensors (sensor_id)
);

SELECT create_hypertable(
    'public.measurements',
    by_range('time'),
    if_not_exists => TRUE
);

ALTER TABLE public.measurements OWNER TO dt_admin;

