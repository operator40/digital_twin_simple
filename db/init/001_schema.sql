CREATE TABLE public.asset_failure_types (
    asset_failure_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    asset_id BIGINT NOT NULL,
    failure_type_id BIGINT,
    default_occurrence_probability REAL,
    severity INTEGER,
    asset_failurecause_id BIGINT,
    CONSTRAINT pk_asset_failure_types PRIMARY KEY (asset_failure_type_id),
    CONSTRAINT fk_asset_failure_types_assets
